type realVectorCase struct {
	name            string
	data            []byte
	segmented       bool
	frameKind       hdlc.FrameKind
	dstRaw          uint32
	srcRaw          uint32
	informationSize int
}

var realVectors = []realVectorCase{
	{"SNRM request", kRealSnrmRequest, false, hdlc.FrameKindUnnumbered, 0x90, 0x30, 0},
	{"UA response", kRealUaResponse, false, hdlc.FrameKindUnnumbered, 0x30, 0x90, 23},
	{"I-frame with LLC payload", kRealInformationWithLlcPayload, false, hdlc.FrameKindInformation, 0x90, 0x30, 71},
	{"RR response", kRealReceiveReady, false, hdlc.FrameKindSupervisory, 0x90, 0x30, 0},
	{"DISC request", kRealDiscRequest, false, hdlc.FrameKindUnnumbered, 0x90, 0x30, 0},
	{"Historical SNRM request", kHistSnrmRequest, false, hdlc.FrameKindUnnumbered, 0x91, 0x64, 0},
	{"Historical UA response", kHistUaResponse, false, hdlc.FrameKindUnnumbered, 0x64, 0x91, 21},
	{"Historical DISC request", kHistDiscRequest, false, hdlc.FrameKindUnnumbered, 0x91, 0x64, 0},
	{"Historical RR response", kHistReceiveReady, false, hdlc.FrameKindSupervisory, 0x91, 0x64, 0},
	{"Historical I-frame with LLC payload", kHistInformationWithLlcPayload, false, hdlc.FrameKindInformation, 0x91, 0x64, 16},
}

func TestRealVectorsDecodeAndReencode(t *testing.T) {
	limits := hdlc.DefaultCodecLimits()

	for _, tc := range realVectors {
		tc := tc
		t.Run(tc.name, func(t *testing.T) {
			frame, err := hdlc.DecodeFrame(tc.data, limits)
			if err != nil {
				t.Fatalf("DecodeFrame: %v", err)
			}

			if frame.Segmented != tc.segmented {
				t.Errorf("segmented: got %v, want %v", frame.Segmented, tc.segmented)
			}
			if frame.Control.FrameKind() != tc.frameKind {
				t.Errorf("frameKind: got %v, want %v", frame.Control.FrameKind(), tc.frameKind)
			}
			if frame.Destination.RawValue() != tc.dstRaw {
				t.Errorf("dst raw: got 0x%02x, want 0x%02x", frame.Destination.RawValue(), tc.dstRaw)
			}
			if frame.Source.RawValue() != tc.srcRaw {
				t.Errorf("src raw: got 0x%02x, want 0x%02x", frame.Source.RawValue(), tc.srcRaw)
			}
			if len(frame.Information) != tc.informationSize {
				t.Fatalf("info size: got %d, want %d", len(frame.Information), tc.informationSize)
			}

			if tc.frameKind == hdlc.FrameKindInformation {
				if len(frame.Information) < 3 ||
					frame.Information[0] != 0xe6 ||
					frame.Information[1] != 0xe6 ||
					frame.Information[2] != 0x00 {
					t.Errorf("LLC header: got %x", frame.Information[:3])
				}
			}

			reencoded, err := hdlc.EncodeFrame(frame, limits)
			if err != nil {
				t.Fatalf("EncodeFrame: %v", err)
			}
			if !bytes.Equal(reencoded, tc.data) {
				t.Errorf("re-encoded differs\ngot:  %x\nwant: %x", reencoded, tc.data)
			}
		})
	}
}
